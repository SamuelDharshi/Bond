// Turns the cashc JSON artifact into a typed `as const` TS module so CashScript can infer
// constructor/unlock argument types.
import { readFileSync, writeFileSync } from 'node:fs';
const json = readFileSync(new URL('../src/artifact/Bond.json', import.meta.url), 'utf8');
const a = JSON.parse(json);
a.updatedAt = '2026-01-01T00:00:00.000Z'; // fixed so the committed artifact is deterministic
writeFileSync(new URL('../src/artifact/Bond.json', import.meta.url), JSON.stringify(a, null, 2) + '\n');
writeFileSync(
  new URL('../src/artifact/Bond.artifact.ts', import.meta.url),
  `// GENERATED by scripts/artifact-to-ts.mjs from Bond.json — do not edit.\nconst artifact = ${JSON.stringify(a, null, 2)} as const;\nexport default artifact;\n`,
);
console.log('artifact written:', a.contractName, 'cashc', a.compiler.version);
