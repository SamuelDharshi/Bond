// Records real txids to docs/demo-txids.json and renders docs/DEMO_TXIDS.md from it.
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { getNetwork } from '@bond/core';
import { ROOT } from './env.js';

const JSON_PATH = resolve(ROOT, 'docs', 'proof', 'demo-txids.json');
const MD_PATH = resolve(ROOT, 'docs', 'proof', 'DEMO_TXIDS.md');

interface Entry {
  label: string;
  txid?: string;
  note?: string;
  network: string;
  at: string;
}
type Log = Record<string, Entry[]>;

function load(): Log {
  return existsSync(JSON_PATH) ? (JSON.parse(readFileSync(JSON_PATH, 'utf8')) as Log) : {};
}

/** Start a fresh section (e.g. one e2e run) so old runs don't accumulate. */
export function resetSection(section: string): void {
  const log = load();
  log[section] = [];
  save(log);
}

export function record(section: string, label: string, txid?: string, note?: string): void {
  const log = load();
  (log[section] ??= []).push({ label, txid, note, network: getNetwork().name, at: new Date().toISOString() });
  save(log);
  const url = txid ? getNetwork().explorerTx(txid) : '';
  console.log(`  [tx] ${label}${txid ? `: ${txid}  ${url}` : ''}${note ? `  (${note})` : ''}`);
}

function save(log: Log): void {
  mkdirSync(resolve(ROOT, 'docs', 'proof'), { recursive: true });
  writeFileSync(JSON_PATH, JSON.stringify(log, null, 2) + '\n');
  const net = getNetwork();
  const lines = [
    '# Demo & test transaction ids',
    '',
    '_Generated by `pnpm e2e` / `pnpm demo:seed` from `docs/proof/demo-txids.json`. Every txid below was built, signed and broadcast to a real network._',
    '',
  ];
  for (const [section, entries] of Object.entries(log)) {
    lines.push(`## ${section}`, '', '| What | Network | Txid / result |', '|---|---|---|');
    for (const e of entries) {
      const link = e.txid
        ? `[\`${e.txid.slice(0, 16)}…\`](${e.network === net.name ? net.explorerTx(e.txid) : e.txid})`
        : '';
      lines.push(`| ${e.label} | ${e.network} | ${[link, e.note].filter(Boolean).join(' — ')} |`);
    }
    lines.push('');
  }
  writeFileSync(MD_PATH, lines.join('\n'));
}
